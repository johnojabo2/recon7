ALLOW_ALL_SCOPES_DEV=${INPUT_SCOPE_DEV:-false}
echo -e "${GREEN}Scope Bypass set to: ${ALLOW_ALL_SCOPES_DEV}${NC}"
echo ""

# 4. Optional Integrations Credentials
echo -e "${CYAN}[Step 3/4] Optional External API Keys${NC}"
echo -e "${YELLOW}Tip: If you do not have API keys right now, press ENTER on each prompt to skip.${NC}"
echo "Recon7 runs core features out of the box using free passive sources without API keys."
echo ""
