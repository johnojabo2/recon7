read -p "Google Search API Key (Optional - Press ENTER to skip): " GOOGLE_SEARCH_API_KEY
read -p "Google Search Engine ID (Optional - Press ENTER to skip): " GOOGLE_SEARCH_ENGINE_ID
echo ""

# Write .env file
