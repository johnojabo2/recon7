# Auto-generated by Recon7 Installation Wizard
ENVIRONMENT=production
DEBUG=False

# Database Configuration
POSTGRES_DB=recon7
POSTGRES_USER=postgres
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
DATABASE_URL=postgresql://postgres:${POSTGRES_PASSWORD}@postgres:5432/recon7

# Scope Authorization Gate
ALLOW_ALL_SCOPES_DEV=${ALLOW_ALL_SCOPES_DEV}

# OSINT Credentials
GITHUB_TOKEN=${GITHUB_TOKEN}
GOOGLE_SEARCH_API_KEY=${GOOGLE_SEARCH_API_KEY}
GOOGLE_SEARCH_ENGINE_ID=${GOOGLE_SEARCH_ENGINE_ID}
EOF

echo -e "${GREEN}✓ Configuration saved to .env${NC}"
echo ""

# Build & Deploy Containers
echo -e "${YELLOW}Building unified Docker image (johnojabo1/recon7) and starting services...${NC}"
${DOCKER_COMPOSE_CMD} build
${DOCKER_COMPOSE_CMD} up -d

