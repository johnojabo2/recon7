echo "This installer configures your environment credentials, builds"
echo "the unified Recon7 container (johnojabo1/recon7), and deploys"
echo "the complete stack (Web Console + API + Worker + PostgreSQL)."
echo ""

# 1. Check Docker & Docker Compose installation
if ! command -v docker &> /dev/null; then
    echo -e "${RED}[ERROR] Docker is not installed or not in PATH. Please install Docker first.${NC}"
    exit 1
fi

if ! docker compose version &> /dev/null && ! command -v docker-compose &> /dev/null; then
    echo -e "${RED}[ERROR] Docker Compose is not installed. Please install Docker Compose first.${NC}"
    exit 1
fi

DOCKER_COMPOSE_CMD="docker compose"
if ! docker compose version &> /dev/null; then
    DOCKER_COMPOSE_CMD="docker-compose"
fi

# 2. Database Password
echo -e "${CYAN}[Step 1/4] Database Security Credentials${NC}"
echo -e "${YELLOW}Tip: Press ENTER to use default password ('reconpassword123').${NC}"
read -s -p "Enter PostgreSQL password [Press ENTER for default]: " INPUT_DB_PASS
echo ""
POSTGRES_PASSWORD=${INPUT_DB_PASS:-reconpassword123}
echo -e "${GREEN}Database password configured.${NC}"
echo ""

# 3. Operational Environment & Security Scopes
echo -e "${CYAN}[Step 2/4] Scope Authorization Settings${NC}"
echo -e "${YELLOW}Tip: Press ENTER to keep strict production security ('false').${NC}"
echo "Setting to 'true' bypasses target pre-approval for rapid local dev testing."
